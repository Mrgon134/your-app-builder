export function getEbookTranslations(langCode: string): EbookI18nDictionary {
  const code = (langCode || "").toLowerCase() as EbookLanguageCode;
  return EBOOK_TRANSLATIONS[code] || EBOOK_TRANSLATIONS.en;
}

export function getEbookLanguageMeta(langCode: string): EbookLanguageMeta {
  const code = (langCode || "").toLowerCase() as EbookLanguageCode;
  return EBOOK_LANGUAGES.find((l) => l.code === code) || EBOOK_LANGUAGES[0];
}
